#!/usr/bin/env python3
"""PROP HUNTER premium SVG master renderer (safe offline, no Telegram calls).

Production mode requires verified bookmaker prices and genuine source assets.
Blank previews are generated by build_masters.py and never treated as tips.
"""
from __future__ import annotations
import base64, io, json, re
from pathlib import Path
from xml.etree import ElementTree as ET
from PIL import Image, ImageFont
import cairosvg

ROOT=Path(__file__).resolve().parent
NS='http://www.w3.org/2000/svg'
XLINK='http://www.w3.org/1999/xlink'
ET.register_namespace('',NS)
ET.register_namespace('xlink',XLINK)


def _price(value):
    try:
        n=float(str(value).strip().replace('@','').replace(',','.'))
    except (ValueError,TypeError):
        return False
    return 1.0 < n < 100000.0


def render_svg(template_key: str, values: dict, images: dict[str,bytes], *,
               strict: bool=True, embed_background:bool=True) -> str:
    manifest=json.loads((ROOT/'manifest.json').read_text(encoding='utf-8'))
    info=manifest['templates'].get(template_key)
    if info is None:
        # Extra 7-leg Builder and 7–12-leg multi-game cards inherit exactly the
        # same layered NBA v2 visual source, extended in height, not a generic
        # fallback poster. These are DERIVED masters, not user-uploaded originals.
        import re as _re
        match=_re.fullmatch(r'(builder|cross_game|combo|lottery)_(\d+)',str(template_key))
        if match is None:
            raise ValueError('Unknown master: '+str(template_key))
        family,n=match.group(1),int(match.group(2))
        max_legs=7 if family=='builder' else 12
        if not 7<=n<=max_legs:
            raise ValueError('Unsupported extended master: '+str(template_key))
        from build_masters import multi
        info={'family':family,'legs':n,'derived':True}
        raw=multi(family,n)
    else:
        raw=(ROOT/info['file']).read_text(encoding='utf-8')
    if not isinstance(values,dict) or not isinstance(images,dict):
        raise TypeError('values and images must be dictionaries')
    if embed_background:
        bg=(ROOT/'assets'/'arena.jpg').read_bytes()
        raw=raw.replace('xlink:href="assets/arena.jpg"',
                        'xlink:href="data:image/jpeg;base64,'+base64.b64encode(bg).decode('ascii')+'"')
        logo=(ROOT/'assets'/'nba_logo.png').read_bytes()
        raw=raw.replace('xlink:href="assets/nba_logo.png"',
                        'xlink:href="data:image/png;base64,'+base64.b64encode(logo).decode('ascii')+'"')
    root=ET.fromstring(raw)
    fields={e.get('data-field') for e in root.iter() if e.get('data-field')}
    slots={e.get('data-image-slot') for e in root.iter() if e.get('data-image-slot')}
    if strict:
        # Never invent a bookmaker price, probability, hit rate, or combined odds.
        if values.get('odds_verified') is not True:
            raise ValueError('Bookmaker odds must be independently verified')
        if info['family'] in ('single','longshot'):
            if not _price(values.get('odds')):raise ValueError('Verified single price missing')
        elif info['family']=='ladder':
            for i in range(1,info['legs']+1):
                if not _price(values.get(f'leg_{i}_odds')):
                    raise ValueError(f'Verified ladder rung {i} price missing')
        else:
            if not _price(values.get('total_odds')):
                raise ValueError('Valid numeric combination price missing')
            if values.get('combo_quote_verified') is not True:
                if values.get('combo_quote_calculated') is not True:
                    raise ValueError('Neither observed nor calculated combo quote is labelled')
                # A calculated total is ONLY a display reference. It must
                # derive from independently observed positive leg quotes.
                import math
                prices=[]
                for i in range(1,info['legs']+1):
                    raw_price=values.get(f'leg_{i}_odds')
                    if not _price(raw_price):
                        raise ValueError(f'Observed individual leg quote {i} missing')
                    prices.append(float(str(raw_price).replace('@','').replace(',','.')))
                product=math.prod(prices)
                reported=float(str(values['total_odds']).replace('@','').replace(',','.'))
                if not math.isfinite(product) or abs(product-reported)>max(.02,product*.0001):
                    raise ValueError('Calculated combo quote differs from genuine leg prices')
        multi_game=info['family'] in ('lottery','combo','cross_game')
        if multi_game:
            if not all(str(values.get(f'leg_{i}_game') or '').strip() for i in range(1,info['legs']+1)):
                raise ValueError('Every multi-game leg requires its verified matchup and tipoff')
        elif not all(str(values.get(k) or '').strip() for k in ('date','time','home_name','away_name')):
            raise ValueError('Verified matchup and tipoff are required')
        required=set() if multi_game else {'home_logo','away_logo'}
        if info['family'] in ('single','longshot','ladder','same_player'):
            required.add('player_photo')
        if info['family'] in ('builder','cross_game','lottery'):
            required.update(f'leg_{i}_photo' for i in range(1,info['legs']+1))
        missing=required-set(k for k,v in images.items() if v)
        if missing:raise ValueError('Missing authentic images: '+', '.join(sorted(missing)))
    if values.get('combo_quote_calculated') is True:
        # Relabel the existing total-quote heading within the exact same
        # premium panel; a multiplied SGP price is NOT book confirmed.
        for e in root.iter():
            if (e.tag.endswith('text') and (e.text or '').strip()=='GESAMTQUOTE'):
                e.text='BERECHNETE QUOTE'
    for e in root.iter():
        key=e.get('data-field')
        if key is not None:
            value=values.get(key)
            e.text=str(value).strip() if value is not None else ''
            # Shrink only as necessary, preserve readable min font.
            if e.text and len(e.text)>20:
                original=float(e.get('font-size') or 28)
                maxlen=24 if key.endswith('_market') else 20
                e.set('font-size',str(round(min(original,max(12,original*maxlen/len(e.text))),1)))
            # Explicit geometry slots are sized by actual glyph width, not
            # character count. Never let a long name run into match metadata.
            limit=e.get('data-max-width')
            if e.text and limit is not None:
                size=max(12,int(float(e.get('font-size') or 28)))
                font_name=('DejaVuSans-BoldOblique.ttf'
                           if e.get('font-style')=='italic' else 'DejaVuSans-Bold.ttf')
                while True:
                    font=ImageFont.truetype(font_name,size)
                    bbox=font.getbbox(e.text)
                    if max(font.getlength(e.text),bbox[2]-min(0,bbox[0]))<=float(limit)-6:
                        break
                    if size<=12:
                        raise ValueError('Text does not fit reserved master field: '+key)
                    size-=1
                e.set('font-size',str(size))
        slot=e.get('data-image-slot')
        if not slot or not images.get(slot):continue
        data=images[slot]
        if not isinstance(data,bytes):raise TypeError(slot+': image bytes required')
        try:
            with Image.open(io.BytesIO(data)) as im:
                im.load()
                if im.format!='PNG':raise ValueError(slot+': PNG required')
                portrait=(slot=='player_photo' or slot.endswith('_photo'))
                if portrait and im.convert('RGBA').getchannel('A').getextrema()[0]==255:
                    raise ValueError(slot+': transparent athlete cutout required')
        except (OSError,Image.UnidentifiedImageError) as exc:
            raise ValueError(slot+': invalid image') from exc
        image=ET.SubElement(e,f'{{{NS}}}image')
        for k in ('x','y','width','height'):
            image.set(k,e.get('data-'+k))
        image.set('preserveAspectRatio','xMidYMax meet' if portrait else 'xMidYMid meet')
        image.set(f'{{{XLINK}}}href','data:image/png;base64,'+base64.b64encode(data).decode('ascii'))
    return ET.tostring(root,encoding='unicode')


def render_png(template_key:str, values:dict, images:dict[str,bytes],*,strict:bool=True)->bytes:
    svg=render_svg(template_key,values,images,strict=strict)
    root=ET.fromstring(svg)
    height=int(float(root.get('height') or '1440'))
    return cairosvg.svg2png(bytestring=svg.encode('utf-8'),
                            output_width=1080,output_height=height)
